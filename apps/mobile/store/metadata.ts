// Pure builders behind `store:metadata`: the site URL guard, the EAS Metadata
// file (App Store), and the paste ready Play copy. No I/O here; the script in
// scripts/store-metadata.ts reads the env and writes the files.
// Spec: docs/specs/0057-store-listing-app-icon/index.md (AC-5)
import type { AppStoreLocale, StoreListing } from "./listing/types";

export type SiteUrlResult =
  { readonly ok: true; readonly origin: string } | { readonly ok: false; readonly reason: string };

const IPV4 = /^\d{1,3}(\.\d{1,3}){3}$/;

/**
 * Accepts only a real production origin: https, not localhost, not an IP
 * literal, not a Vercel preview host, and nothing containing "example".
 */
export const checkSiteUrl = (raw: string | undefined): SiteUrlResult => {
  const value = (raw ?? "").trim();
  if (value.length === 0) return { ok: false, reason: "NEXT_PUBLIC_SITE_URL is not set" };

  const parsed = URL.canParse(value) ? new URL(value) : null;
  if (parsed === null) return { ok: false, reason: `"${value}" is not a URL` };
  if (parsed.protocol !== "https:") return { ok: false, reason: `"${value}" is not https` };

  const host = parsed.hostname.toLowerCase();
  if (host === "localhost") return { ok: false, reason: `"${value}" points at localhost` };
  if (IPV4.test(host) || host.startsWith("[")) {
    return { ok: false, reason: `"${value}" is an IP address` };
  }
  if (host.endsWith(".vercel.app")) {
    return { ok: false, reason: `"${value}" is a Vercel preview host` };
  }
  if (host.includes("example")) return { ok: false, reason: `"${value}" is a placeholder host` };

  return { ok: true, origin: parsed.origin.replace(/\/$/, "") };
};

export const STORE_CATEGORIES = ["FOOD_AND_DRINK", "LIFESTYLE"] as const;

export interface AppStoreInfo {
  readonly title: string;
  readonly subtitle: string;
  readonly keywords: readonly string[];
  readonly promoText: string;
  readonly description: string;
  readonly releaseNotes?: string;
  readonly supportUrl: string;
  readonly privacyPolicyUrl: string;
  readonly marketingUrl: string;
}

/** The EAS Metadata `store.config.json` shape (configVersion 0). */
export interface StoreConfig {
  readonly configVersion: 0;
  readonly apple: {
    readonly categories: readonly string[];
    readonly info: Readonly<Partial<Record<AppStoreLocale, AppStoreInfo>>>;
  };
}

export interface BuildOptions {
  readonly withReleaseNotes: boolean;
}

const appStoreInfo = (
  listing: StoreListing,
  origin: string,
  { withReleaseNotes }: BuildOptions,
): AppStoreInfo => ({
  title: listing.appStore.name,
  subtitle: listing.appStore.subtitle,
  keywords: listing.appStore.keywords,
  promoText: listing.appStore.promotionalText,
  description: listing.appStore.description,
  ...(withReleaseNotes ? { releaseNotes: listing.releaseNotes } : {}),
  supportUrl: `${origin}/${listing.locale}/privacy#contact`,
  privacyPolicyUrl: `${origin}/${listing.locale}/privacy`,
  marketingUrl: `${origin}/${listing.locale}`,
});

export const buildStoreConfig = (
  listings: readonly StoreListing[],
  origin: string,
  options: BuildOptions,
): StoreConfig => ({
  configVersion: 0,
  apple: {
    categories: STORE_CATEGORIES,
    info: Object.fromEntries(
      listings.map((listing) => [listing.appStore.locale, appStoreInfo(listing, origin, options)]),
    ),
  },
});

const playSection = (listing: StoreListing): string =>
  [
    `## ${listing.play.locale}`,
    "",
    "### Title",
    "",
    listing.play.title,
    "",
    "### Short description",
    "",
    listing.play.shortDescription,
    "",
    "### Full description",
    "",
    listing.play.fullDescription,
    "",
    "### Release notes",
    "",
    `<${listing.play.locale}>`,
    listing.releaseNotes,
    `</${listing.play.locale}>`,
  ].join("\n");

/** Paste ready Play Console copy, one section per Play locale. */
export const buildPlayMarkdown = (listings: readonly StoreListing[]): string =>
  [
    "# Google Play listing copy",
    "",
    "Generated by `pnpm --filter mobile store:metadata` from `store/listing/`. Edit the modules, not this file.",
    "",
    listings.map(playSection).join("\n\n"),
    "",
  ].join("\n");
